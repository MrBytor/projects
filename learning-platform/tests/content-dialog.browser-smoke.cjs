/* Offline UI smoke: every browser request is fulfilled locally or aborted. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fixture = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const output = path.resolve(process.argv[3]);
const platform = path.resolve(__dirname, '..');
const origin = 'https://lms-preview.test';
const reports = [];
const postBodies = [];
let postResponse = 'invalid';
let courseLoads = 0;
let videoBytes = null;
let releaseVideoUpload = null;
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CONTENT_UI_BROWSER ? { executablePath: process.env.CONTENT_UI_BROWSER } : {}) });
  const context = await browser.newContext({ viewport: { width: 1360, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', async route => {
    const request = route.request();
    const url = new URL(request.url());
    if (url.origin !== origin) return route.abort();
    if (request.method() === 'POST') {
      postBodies.push(request.postData() || '');
      if (postResponse === 'video-upload') await new Promise(resolve => { releaseVideoUpload = resolve; });
      if (postResponse === 'video-upload') return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ redirect: fixture.success_redirect }) });
      if (postResponse === 'success') return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ redirect: fixture.success_redirect }) });
      return route.fulfill({ contentType: 'text/html; charset=utf-8', body: fixture.invalid_folder_html });
    }
    const key = url.pathname + url.search;
    if (key === fixture.video_stream_url && videoBytes) return route.fulfill({ contentType: 'video/webm', body: videoBytes, headers: { 'Accept-Ranges': 'bytes' } });
    if (key === fixture.browser_url) courseLoads++;
    if (fixture.routes[key]) return route.fulfill({ contentType: 'text/html; charset=utf-8', body: fixture.routes[key] });
    if (url.pathname.startsWith('/platform-assets/')) {
      const asset = path.resolve(platform, 'assets', url.pathname.substring('/platform-assets/'.length));
      if (!asset.startsWith(path.join(platform, 'assets') + path.sep) || !fs.existsSync(asset)) return route.abort();
      return route.fulfill({ contentType: asset.endsWith('.css') ? 'text/css' : 'text/javascript', body: fs.readFileSync(asset) });
    }
    if (url.pathname.startsWith('/design-assets/fonts/')) {
      const asset = path.resolve(platform, '../academic-preview/assets/fonts', path.basename(url.pathname));
      if (fs.existsSync(asset)) return route.fulfill({ body: fs.readFileSync(asset), contentType: asset.endsWith('.css') ? 'text/css' : 'font/woff2' });
    }
    if (url.pathname === '/design-assets/statistics.jpg') return route.fulfill({ body: fs.readFileSync(path.resolve(platform, '../academic-preview/assets/statistics.jpg')), contentType: 'image/jpeg' });
    return route.fulfill({ status: 404, body: '' });
  });
  await page.goto(origin + fixture.browser_url);
  const moduleFolder = page.locator(`[data-content-folder="${fixture.module_id}"]`);
  const lessonFolder = page.locator(`[data-content-folder="${fixture.lesson_id}"]`);
  const resourcesFolder = page.locator(`[data-content-folder="${fixture.resources_id}"]`);
  const folderOpen = folder => folder.evaluate(element => element.open);
  if (await folderOpen(moduleFolder)) await moduleFolder.locator(':scope > summary').click();
  const loadsBeforeExpand = courseLoads;
  await moduleFolder.locator(':scope > summary .content-folder-arrow').click();
  assert(await folderOpen(moduleFolder));
  await lessonFolder.locator(':scope > summary').getByText(/Calculations in context/).click();
  assert(await folderOpen(lessonFolder));
  await resourcesFolder.locator(':scope > summary').click();
  assert(await folderOpen(resourcesFolder));
  await page.getByRole('link', { name: 'Practice reference', exact: true }).waitFor({ state: 'visible' });
  assert.equal(page.url(), origin + fixture.browser_url);
  assert.equal(courseLoads, loadsBeforeExpand);
  await resourcesFolder.locator(':scope > summary').focus();
  await page.keyboard.press('Enter');
  assert.equal(await folderOpen(resourcesFolder), false);
  reports.push('Folder arrows and names expand nested materials in place; keyboard Enter collapses them without navigation.');
  await page.waitForFunction(({ moduleId, lessonId, resourceId }) => {
    const tree = document.querySelector('[data-folder-storage-key]');
    const state = JSON.parse(sessionStorage.getItem(tree.dataset.folderStorageKey) || '[]');
    return state.includes(String(moduleId)) && state.includes(String(lessonId)) && !state.includes(String(resourceId));
  }, { moduleId: fixture.module_id, lessonId: fixture.lesson_id, resourceId: fixture.resources_id });
  await page.reload();
  assert(await folderOpen(moduleFolder));
  assert(await folderOpen(lessonFolder));
  assert.equal(await folderOpen(resourcesFolder), false);
  reports.push('Reload restores expanded folders and leaves collapsed subfolders closed.');
  const lessonAddMenu = lessonFolder.locator('.content-add-menu').first();
  await lessonAddMenu.locator(':scope > summary').click();
  const menuLinks = await lessonAddMenu.locator('a').evaluateAll(links => links.map(link => {
    const url = new URL(link.href);
    return [url.searchParams.get('kind'), url.searchParams.get('parent')];
  }));
  assert.deepEqual(menuLinks, ['folder', 'file', 'page', 'video', 'link', 'test'].map(kind => [kind, String(fixture.lesson_id)]));
  reports.push('All six Add materials destinations target the expanded class folder.');
  await page.screenshot({ path: path.join(output, 'materials-menu-desktop.png'), fullPage: true });
  await lessonAddMenu.getByRole('link', { name: 'Add folder', exact: true }).click();
  const dialog = page.locator('#content-dialog');
  await dialog.locator('[name=title]').waitFor();
  const box = await dialog.boundingBox();
  assert(Math.abs(box.x + box.width / 2 - 680) < 2);
  assert(Math.abs(box.y + box.height / 2 - 450) < 2);
  assert.equal(await dialog.locator('[data-availability-dates]').getAttribute('open'), null);
  await page.screenshot({ path: path.join(output, 'add-folder-desktop.png') });
  await dialog.locator('[name=availability]').selectOption('scheduled');
  assert.notEqual(await dialog.locator('[data-availability-dates]').getAttribute('open'), null);
  reports.push('Folder modal is centered; availability dates are collapsed and expand for Scheduled.');
  await dialog.locator('[name=availability]').selectOption('published');
  await dialog.locator('[name=title]').fill('New teaching folder');
  await dialog.locator('button[type="submit"]').click();
  await dialog.locator('.content-form-error').waitFor();
  assert.equal(page.url(), origin + fixture.browser_url);
  assert(postBodies[0].includes('name="account_id"'));
  assert(postBodies[0].includes('name="csrfmiddlewaretoken"'));
  assert.equal(await dialog.getAttribute('open'), '');
  reports.push('Server validation stays inside the modal and carries account ID plus CSRF.');
  await page.keyboard.press('Escape');
  assert.equal(await dialog.getAttribute('open'), null);
  await page.waitForFunction(() => document.body.style.overflow === '');
  assert.equal(await page.evaluate(() => document.body.style.overflow), '');
  assert.equal(await page.evaluate(() => document.activeElement.matches('.content-add-menu > summary')), true);
  reports.push('Escape closes the modal, restores scrolling, and returns focus to Add materials.');
  postResponse = 'success';
  await lessonAddMenu.locator(':scope > summary').click();
  await lessonAddMenu.getByRole('link', { name: 'Add folder', exact: true }).click();
  await dialog.locator('[name=title]').fill('New teaching folder');
  const loadsBeforeSave = courseLoads;
  const reloaded = page.waitForResponse(response => response.request().method() === 'GET' && new URL(response.url()).pathname === fixture.browser_url);
  await dialog.locator('button[type="submit"]').click();
  await reloaded;
  await page.waitForLoadState();
  assert(courseLoads > loadsBeforeSave);
  assert.equal(page.url(), origin + fixture.success_redirect);
  assert(await folderOpen(moduleFolder));
  assert(await folderOpen(lessonFolder));
  reports.push('Successful material save reloads course content and returns to the expanded class in place.');
  await page.evaluate(() => sessionStorage.clear());
  await page.goto(origin + fixture.browser_url + `#folder-${fixture.resources_id}`);
  await page.reload();
  assert(await folderOpen(moduleFolder));
  assert(await folderOpen(lessonFolder));
  assert(await folderOpen(resourcesFolder));
  reports.push('Direct folder anchors open the target and all ancestors.');
  await page.setViewportSize({ width: 320, height: 740 });
  await lessonAddMenu.locator(':scope > summary').click();
  await lessonAddMenu.getByRole('link', { name: 'Add folder', exact: true }).click();
  await dialog.locator('[name=title]').waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const mobile = await dialog.boundingBox();
  assert(mobile.x >= 0 && mobile.x + mobile.width <= 320);
  assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), true);
  await page.screenshot({ path: path.join(output, 'add-folder-mobile.png') });
  reports.push('320px view has no horizontal overflow in either document or dialog.');
  await page.keyboard.press('Escape');
  const recordedVideo = await page.evaluate(async () => {
    const canvas = document.createElement('canvas');
    canvas.width = 640; canvas.height = 360;
    const drawing = canvas.getContext('2d');
    const stream = canvas.captureStream(12);
    const recorder = new MediaRecorder(stream, { mimeType: 'video/webm;codecs=vp8' });
    const chunks = [];
    recorder.ondataavailable = event => chunks.push(event.data);
    const done = new Promise(resolve => { recorder.onstop = resolve; });
    recorder.start();
    for (let frame = 0; frame < 18; frame++) {
      drawing.fillStyle = '#173d5d'; drawing.fillRect(0, 0, 640, 360);
      drawing.fillStyle = '#ffffff'; drawing.font = '32px sans-serif'; drawing.fillText('Statistics: worked example', 50, 115);
      drawing.fillStyle = '#72b5d7'; drawing.fillRect(50, 195, 30 + frame * 25, 35);
      await new Promise(resolve => setTimeout(resolve, 90));
    }
    recorder.stop(); await done; stream.getTracks().forEach(track => track.stop());
    const bytes = new Uint8Array(await new Blob(chunks, { type: 'video/webm' }).arrayBuffer());
    return Array.from(bytes);
  });
  videoBytes = Buffer.from(recordedVideo);
  fs.writeFileSync(path.join(output, 'synthetic-lesson.webm'), videoBytes);
  await lessonAddMenu.locator(':scope > summary').click();
  await lessonAddMenu.getByRole('link', { name: 'Add video', exact: true }).click();
  await dialog.locator('[name=video_source]').first().waitFor();
  assert.equal(await dialog.locator('[name=video_source][value=upload]').isChecked(), true);
  assert.equal(await dialog.locator('[data-field-name=file]').isVisible(), true);
  assert.equal(await dialog.locator('[data-field-name=url]').isVisible(), false);
  assert.equal(await dialog.locator('[name=url]').isDisabled(), true);
  assert((await dialog.locator('[data-field-name=file]').innerText()).includes('100 MB'));
  await dialog.locator('[name=video_source][value=link]').check();
  assert.equal(await dialog.locator('[name=file]').isDisabled(), true);
  assert.equal(await dialog.locator('[data-field-name=url]').isVisible(), true);
  await dialog.locator('[name=url]').fill('https://www.youtube.com/watch?v=dQw4w9WgXcQ');
  await dialog.locator('[name=video_source][value=upload]').check();
  await dialog.locator('[name=file]').evaluate(input => {
    const transfer = new DataTransfer();
    transfer.items.add(new File([new Uint8Array(100 * 1024 * 1024 + 1)], 'too-large.webm', { type: 'video/webm' }));
    input.files = transfer.files;
    input.dispatchEvent(new Event('change', { bubbles: true }));
  });
  assert.equal(await dialog.locator('[name=file]').evaluate(input => input.validity.customError), true);
  assert((await dialog.locator('.content-video-selection').innerText()).includes('exceeds the 100 MB limit'));
  await dialog.locator('[name=file]').setInputFiles({ name: 'worked-example.webm', mimeType: 'video/webm', buffer: videoBytes });
  assert.equal(await dialog.locator('[name=file]').evaluate(input => input.validity.customError), false);
  await dialog.locator('[name=title]').fill('Worked example video');
  assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), true);
  await page.screenshot({ path: path.join(output, 'add-video-mobile.png') });
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.screenshot({ path: path.join(output, 'add-video-desktop.png') });
  postResponse = 'video-upload';
  const uploaded = page.waitForResponse(response => response.request().method() === 'GET' && new URL(response.url()).pathname === fixture.browser_url);
  await dialog.locator('button[type=submit]').click();
  await dialog.getByRole('button', { name: 'Uploading video…', exact: true }).waitFor();
  assert.equal(await dialog.locator('button[type=submit]').isDisabled(), true);
  while (!releaseVideoUpload) await new Promise(resolve => setTimeout(resolve, 10));
  releaseVideoUpload(); await uploaded;
  await page.locator('#content-dialog[open]').waitFor({ state: 'hidden' });
  await page.waitForLoadState();
  const videoBody = postBodies.at(-1);
  assert(videoBody.includes('name="video_source"'));
  assert(videoBody.includes('filename="worked-example.webm"'));
  assert.equal(videoBody.includes('name="url"'), false);
  reports.push('Video dialog switches upload/link controls, validates the 100 MB client limit, fits mobile, and shows upload busy state.');
  await page.goto(origin + fixture.video_detail_url);
  const player = page.locator('[data-content-video]');
  await page.waitForFunction(() => document.querySelector('[data-content-video]')?.readyState >= 1);
  assert.equal(await player.getAttribute('controls'), '');
  assert.equal(await player.getAttribute('autoplay'), null);
  assert.equal(await player.getAttribute('playsinline'), '');
  assert.equal(await player.locator('source').getAttribute('src'), fixture.video_stream_url);
  assert.equal(await page.getByRole('link', { name: 'Download video', exact: true }).getAttribute('href'), fixture.video_download_url);
  await player.evaluate(video => video.play());
  await page.waitForFunction(() => document.querySelector('[data-content-video]').currentTime > 0.3);
  await player.evaluate(video => video.pause());
  assert.equal(await player.evaluate(video => video.paused), true);
  await page.screenshot({ path: path.join(output, 'video-player-desktop.png') });
  await page.setViewportSize({ width: 320, height: 740 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const videoBox = await player.boundingBox();
  assert(videoBox.x >= 0 && videoBox.x + videoBox.width <= 320);
  await page.screenshot({ path: path.join(output, 'video-player-mobile.png'), fullPage: true });
  await player.evaluate(video => video.dispatchEvent(new Event('error')));
  assert.equal(await page.locator('[data-video-error]').isVisible(), true);
  reports.push('Embedded native player loads a generated WebM, plays and pauses, fits mobile, and offers protected download plus playback-error fallback.');
  await page.goto(origin + fixture.video_embed_url);
  assert.equal(await page.locator('.content-video-embed').getAttribute('src'), 'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ');
  assert.equal(await page.locator('.content-video-embed').getAttribute('allowfullscreen'), '');
  await page.goto(origin + fixture.video_external_url);
  assert.equal(await page.locator('video, .content-video-embed').count(), 0);
  assert.equal(await page.getByRole('link', { name: 'Open video', exact: false }).getAttribute('href'), 'https://example.com/video/lesson');
  reports.push('YouTube links use an embedded player; unsupported providers receive an explicit external video link.');
  const noScriptContext = await browser.newContext({ javaScriptEnabled: false });
  const noScriptPage = await noScriptContext.newPage();
  await noScriptPage.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin === origin && url.pathname + url.search === fixture.standalone_video_url) return route.fulfill({ contentType: 'text/html; charset=utf-8', body: fixture.routes[fixture.standalone_video_url] });
    return route.abort();
  });
  await noScriptPage.goto(origin + fixture.standalone_video_url);
  assert.equal(await noScriptPage.locator('[name=file]').isVisible(), true);
  assert.equal(await noScriptPage.locator('[name=url]').isVisible(), true);
  assert.equal(await noScriptPage.locator('[name=video_source]').count(), 2);
  await noScriptContext.close();
  reports.push('Without JavaScript, the source choice and both upload/link fields remain available.');
  await page.goto(origin + fixture.student_url);
  assert.equal(await page.locator('[data-content-menu], [data-content-dialog], #content-dialog').count(), 0);
  assert.equal(await page.getByText('Teacher planning folder', { exact: true }).count(), 0);
  assert.equal(await page.getByText('Unreleased answers', { exact: true }).count(), 0);
  assert.equal(await folderOpen(moduleFolder), false);
  await moduleFolder.locator(':scope > summary').click();
  await lessonFolder.locator(':scope > summary').click();
  await page.getByRole('link', { name: 'Getting started', exact: true }).waitFor({ state: 'visible' });
  assert.equal(page.url(), origin + fixture.student_url);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: path.join(output, 'student-folders-mobile.png'), fullPage: true });
  reports.push('Student folders expand without teacher controls or hidden descendants, with expansion state separate from the teacher.');
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(output, 'smoke-results.json'), JSON.stringify(reports, null, 2));
  console.log(reports.join('\n'));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
